-- KAGEBOUND future progression datastore policy contract.
-- DataStore persistence is DISABLED by default and must not affect live rewards.
local Shared=game:GetService("ReplicatedStorage"):WaitForChild("KageboundShared")
local Schema=require(Shared:WaitForChild("ProfileSchema"))
local Config=require(Shared:WaitForChild("PersistenceConfig"))
local function check(label,ok)
    assert(ok,"[KAGEBOUND PROFILE SCHEMA FAIL] "..label)
    print("[KAGEBOUND PROFILE SCHEMA PASS] "..label)
end
check("Disabled until Studio save/reload QA",Config.Enabled==false)
local r=Schema.New()
check("Default zero balances",r.shards==0 and r.mastery==0 and r.yokaiDefeats==0)
local a,ok=Schema.Apply(r,"WhispersQuest","first-completion")
check("Quest first reward",ok and a.shards==25 and a.completedWhispers==true)
local b,repeatAward=Schema.Apply(a,"WhispersQuest","first-completion")
check("Quest durable idempotency",not repeatAward and b.shards==25)
local c,k=Schema.Apply(a,"LanternYokai","encounter-0001")
check("Yokai mastery award",k and c.shards==31 and c.mastery==4 and c.yokaiDefeats==1)
local d,again=Schema.Apply(c,"LanternYokai","encounter-0001")
check("Duplicate encounter does not pay twice",not again and d.mastery==4)
local e,newAward=Schema.Apply(d,"LanternYokai","encounter-0002")
check("New encounter pays",newAward and e.shards==37 and e.yokaiDefeats==2)
local bad,accepted=Schema.Apply(e,"OnePieceFruit","whatever")
check("Unknown reward refused",not accepted and bad.shards==37)
check("Future schema is rejected",Schema.Reconcile({version=999})==nil)
check("Out-of-bounds values sanitized",Schema.Reconcile({version=1,shards=-999,mastery=999999999}).shards==0)
print("[KAGEBOUND] Profile migration/idempotency policy ready; actual DataStore tests are pending.")
