-- Studio command bar after Rojo sync; test first, implementation second.
local Shared=game:GetService("ReplicatedStorage"):WaitForChild("KageboundShared")
local Combat=require(Shared:WaitForChild("CombatRules"))
local Profiles=require(Shared:WaitForChild("WeaponAttackRules"))
local kat=Profiles.Resolve("Katana",false,2)
assert(kat and kat.damage==Combat.LightDamage[2])
assert(kat.range==Combat.LightRange)
assert(kat.cooldown==Combat.LightCooldown)
assert(kat.cost==Combat.ActionCost.Light)
assert(kat.windup==Combat.AttackTimeline.Light.windup)
local heavy=Profiles.Resolve("Katana",true,0)
assert(heavy.damage==Combat.HeavyDamage and heavy.range==Combat.HeavyRange)
assert(heavy.guardBreak==Combat.HeavyBreaksParry)
local nodachi=Profiles.Resolve("Nodachi",false,1)
local tanto=Profiles.Resolve("Tanto",false,1)
assert(nodachi and tanto and nodachi.range>kat.range and tanto.range<kat.range)
assert(nodachi.windup>kat.windup and tanto.windup<kat.windup)
assert(nodachi.cooldown>tanto.cooldown)
assert(Profiles.Resolve("Nodachi",true,0).damage>heavy.damage)
assert(not Profiles.Resolve("Tanto",true,0).guardBreak)
local naginata=Profiles.Resolve("Naginata",false,1)
local yari=Profiles.Resolve("Yari",false,1)
assert(naginata and yari)
assert(yari.range>naginata.range and yari.width<naginata.width)
assert(Profiles.Resolve("Naginata",true,0).guardBreak)
assert(not Profiles.Resolve("Yari",true,0).guardBreak)
assert(require(Shared:WaitForChild("WeaponRules")).CanSelect("Naginata"))
assert(require(Shared:WaitForChild("WeaponRules")).CanSelect("Yari"))
assert(Profiles.Resolve("Yumi",false,1)==nil)
assert(Profiles.Resolve("Fake",false,1)==nil)
assert(Profiles.Resolve("Katana",false,0)==nil)
assert(Profiles.Resolve("Katana",false,4)==nil)
print("WeaponAttackRules policy contract PASS; not live combat QA")
