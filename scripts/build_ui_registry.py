"""Generate Roblox UIIconRegistry.lua from confirmed Open Cloud asset IDs."""
import json
from pathlib import Path
data = json.loads(Path("assets/ui/icons/v01/roblox_asset_ids.json").read_text())
ids = data["ids"]
names = ("slash","parry","dash","veilfall","kitsune","oni","tengu","ofuda",
         "world_map","quest","inventory","weapon","spirit_shard","dojo","clan","settings")
if any(not isinstance(ids.get(n), int) or ids[n] <= 0 for n in names):
    raise RuntimeError("Missing Roblox asset IDs; refusing to publish incomplete registry")
lines = ["-- Generated by scripts/build_ui_registry.py from verified Roblox Open Cloud IDs.",
         "-- Do not edit IDs manually. Assets may remain under Roblox moderation.",
         "local Icons = {}", "local ids = {"]
lines += [f'    {name} = {ids[name]},' for name in names]
lines += ["}", "function Icons.get(name)",
          "    local id = ids[name]",
          "    if type(id) ~= \"number\" or id <= 0 then return nil end",
          "    return \"rbxassetid://\" .. tostring(id)",
          "end", "function Icons.apply(imageLabel, name)",
          "    local uri = Icons.get(name)",
          "    if uri then imageLabel.Image = uri; imageLabel.Visible = true; return true end",
          "    imageLabel.Visible = false",
          "    return false", "end", "return Icons", ""]
Path("src/shared/UIIconRegistry.lua").write_text("\n".join(lines))
